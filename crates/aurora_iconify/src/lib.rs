#![doc = include_str!("../README.md")]

pub use aurora_iconify_macros::icon_sets;

use std::cmp::Ordering;
use std::marker::PhantomData;

// `SetId`, `CATALOG_HASH`, `__set_enabled`, and the accessor types of the enabled
// sets. The file lives in the source tree, so editors index it directly.
mod sets;
pub use sets::*;

/// Gives the accessors the icon data a crate embeds. `icon_sets!` implements it,
/// so the accessors work without knowing where the data lives.
pub trait Provider {
    /// The SVG of the icon with this ID in `set`, if the crate embeds it.
    fn get(set: SetId, id: u32) -> Option<&'static str>;
    /// The SVG of the icon named `name` in `set`, if the crate embeds it.
    fn find(set: SetId, name: &str) -> Option<&'static str>;
}

/// An icon set chosen at run time with `Icon::from_set`.
pub struct DynIconSet<P> {
    set: SetId,
    provider: PhantomData<fn() -> P>,
}

impl<P: Provider> DynIconSet<P> {
    #[doc(hidden)]
    pub const fn __new(set: SetId) -> Self {
        Self {
            set,
            provider: PhantomData,
        }
    }

    /// Looks up an embedded icon of this set by its original name. Returns
    /// `None` for icons the crate does not embed.
    pub fn by_name(&self, name: &str) -> Option<&'static str> {
        P::find(self.set, name)
    }
}

/// The embedded icons of one set in one crate, as generated by `icon_sets!`.
///
/// The index layout is documented in `aurora_iconify_catalog::index`.
#[doc(hidden)]
pub struct IconTable {
    index: &'static [u8],
    blob: &'static str,
}

impl IconTable {
    /// Wraps the index and the SVG data that `icon_sets!` generated.
    pub const fn new(index: &'static [u8], blob: &'static str) -> Self {
        Self { index, blob }
    }

    /// The SVG of the icon with ID `id`, if it is embedded.
    pub fn get(&self, id: u32) -> Option<&'static str> {
        let count = self.count()?;
        let (mut low, mut high) = (0, count);
        while low < high {
            let mid = low + (high - low) / 2;
            let record = self.record(mid)?;
            match record.id.cmp(&id) {
                Ordering::Less => low = mid + 1,
                Ordering::Greater => high = mid,
                Ordering::Equal => return self.svg(record),
            }
        }
        None
    }

    /// The SVG of the icon named `name`, if it is embedded.
    pub fn find(&self, name: &str) -> Option<&'static str> {
        let count = self.count()?;
        let by_name_at = HEADER_LEN + count * RECORD_LEN;
        let (mut low, mut high) = (0, count);
        while low < high {
            let mid = low + (high - low) / 2;
            let record = self.record(word(self.index, by_name_at + mid * 4)? as usize)?;
            match self.name(record)?.cmp(name.as_bytes()) {
                Ordering::Less => low = mid + 1,
                Ordering::Greater => high = mid,
                Ordering::Equal => return self.svg(record),
            }
        }
        None
    }

    fn count(&self) -> Option<usize> {
        word(self.index, 0).map(|count| count as usize)
    }

    /// Record `i`, which is sorted by icon ID.
    fn record(&self, i: usize) -> Option<Record> {
        if i >= self.count()? {
            return None;
        }
        let at = HEADER_LEN + i * RECORD_LEN;
        Some(Record {
            id: word(self.index, at)?,
            start: word(self.index, at + 4)?,
            len: word(self.index, at + 8)?,
            name_at: word(self.index, at + 12)?,
            name_len: word(self.index, at + 16)?,
        })
    }

    fn name(&self, record: Record) -> Option<&'static [u8]> {
        let names_at = word(self.index, 8)? as usize;
        let start = names_at.checked_add(record.name_at as usize)?;
        let end = start.checked_add(record.name_len as usize)?;
        self.index.get(start..end)
    }

    fn svg(&self, record: Record) -> Option<&'static str> {
        let start = record.start as usize;
        let end = start.checked_add(record.len as usize)?;
        self.blob.get(start..end)
    }
}

/// Bytes of header before the records. See `aurora_iconify_catalog::index`.
const HEADER_LEN: usize = 12;
/// Bytes per record.
const RECORD_LEN: usize = 20;

#[derive(Clone, Copy)]
struct Record {
    id: u32,
    start: u32,
    len: u32,
    name_at: u32,
    name_len: u32,
}

/// The little-endian `u32` at byte offset `at`, if it lies inside `bytes`.
fn word(bytes: &[u8], at: usize) -> Option<u32> {
    let end = at.checked_add(4)?;
    let b = bytes.get(at..end)?;
    Some(u32::from_le_bytes([b[0], b[1], b[2], b[3]]))
}

/// Whether two byte strings are equal. Unlike `str` comparisons, this works in
/// `const fn`, which the generated `__set_enabled` needs.
#[allow(dead_code)] // Only the generated `__set_enabled` calls it, and only when a set is enabled.
const fn bytes_equal(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    let mut i = 0;
    while i < a.len() {
        if a[i] != b[i] {
            return false;
        }
        i += 1;
    }
    true
}

/// The panic for an icon the crate does not embed. `#[track_caller]` on the
/// accessors makes the reported location the caller's.
#[allow(dead_code)] // Only generated code calls it, and only when a set is enabled.
#[cold]
#[inline(never)]
#[track_caller]
fn missing(set: &str, name: &str) -> ! {
    panic!(
        "icon `{set}:{name}` is not embedded: icon_sets! found no reference to it in this crate's \
         sources. List it explicitly (\"{set}\": [\"{name}\"]) or embed the whole set (\"{set}\": all)."
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use aurora_iconify_catalog::index::{Entry, write};

    fn table(entries: &[Entry<'_>], blob: &str) -> IconTable {
        let index: &'static [u8] = Box::leak(write(entries, blob.len() as u32).into_boxed_slice());
        let blob: &'static str = Box::leak(blob.to_string().into_boxed_str());
        IconTable::new(index, blob)
    }

    #[test]
    fn finds_icons_by_id_and_by_name() {
        let t = table(
            &[
                Entry {
                    id: 2,
                    name: "arrow",
                    start: 0,
                    len: 4,
                },
                Entry {
                    id: 7,
                    name: "zebra",
                    start: 4,
                    len: 5,
                },
            ],
            "<a/><bb/>",
        );
        assert_eq!(t.get(2), Some("<a/>"));
        assert_eq!(t.get(7), Some("<bb/>"));
        assert_eq!(t.get(3), None);
        assert_eq!(t.find("zebra"), Some("<bb/>"));
        assert_eq!(t.find("arrow"), Some("<a/>"));
        assert_eq!(t.find("missing"), None);
    }

    #[test]
    fn an_empty_table_finds_nothing() {
        let t = table(&[], "");
        assert_eq!(t.get(0), None);
        assert_eq!(t.find("x"), None);
    }

    #[test]
    fn a_truncated_blob_yields_no_icon() {
        let t = table(
            &[Entry {
                id: 0,
                name: "a",
                start: 0,
                len: 9,
            }],
            "<a/>",
        );
        assert_eq!(t.get(0), None);
        assert_eq!(t.find("a"), None);
    }
}
