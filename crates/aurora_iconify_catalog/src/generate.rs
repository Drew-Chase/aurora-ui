//! Source text for the `aurora_iconify` facade: one icon set's accessors, and the
//! module that lists the sets.

use crate::{SetData, accessor_type_name, method_names, variant_name};
use std::fmt::Write;

/// The accessors of one set: a type `<Set>Icons<P>` with a method for every icon,
/// a `by_name` lookup and a hidden constructor. An icon's ID is its position in
/// the set's sorted name list.
///
/// The text refers to `Provider`, `SetId` and `missing`, which the facade's `sets`
/// module imports. `__set_accessors!` expands it there.
pub fn facade_set_source(set: &SetData, api_base: &str) -> String {
    let prefix = set.prefix;
    let ty = accessor_type_name(prefix);
    let variant = variant_name(prefix);
    let mut out = String::new();

    let _ = writeln!(
        out,
        "#[doc = {:?}]",
        format!("Icons of the `{prefix}` set.")
    );
    let _ = writeln!(
        out,
        "pub struct {ty}<P>(::core::marker::PhantomData<fn() -> P>);"
    );
    let _ = writeln!(out, "impl<P: Provider> {ty}<P> {{");
    let _ = writeln!(out, "    #[doc(hidden)]");
    let _ = writeln!(
        out,
        "    pub const fn __handle() -> Self {{ {ty}(::core::marker::PhantomData) }}"
    );
    let _ = writeln!(
        out,
        "    /// Looks up an embedded icon of this set by its original name, such as `\"arrow-left\"`."
    );
    let _ = writeln!(
        out,
        "    pub fn by_name(&self, name: &str) -> ::core::option::Option<&'static str> {{"
    );
    let _ = writeln!(out, "        P::find(SetId::{variant}, name)");
    let _ = writeln!(out, "    }}");
    // One line per method keeps the generated file small, which matters to the
    // editor indexing it and to rustc.
    for (id, icon, method) in method_names(set.names()) {
        let url = format!("{api_base}/{prefix}/{icon}.svg?width=48&height=48&color=white");
        let _ = writeln!(
            out,
            "    #[cfg_attr(feature = \"previews\", doc = {:?})]",
            format!("![{icon}]({url})")
        );
        let _ = writeln!(out, "    #[inline]\n    #[track_caller]");
        let _ = writeln!(
            out,
            "    pub fn {method}(&self) -> &'static str {{ match P::get(SetId::{variant}, {id}) {{ Some(svg) => svg, None => missing({prefix:?}, {icon:?}) }} }}"
        );
    }
    out.push_str("}\n");
    out
}

/// The facade's `sets` module, given the prefixes of every icon set it can offer
/// and the fingerprint of the catalog they come from.
///
/// It declares `SetId` (one variant per set), `CATALOG_HASH`, and `__set_enabled`.
/// Each set then gets one `#[cfg(feature = ...)]` line that expands to its
/// accessors, so only the sets whose features are enabled are generated. The file
/// is part of the source tree, so editors index it like any other source.
pub fn sets_module_source(prefixes: &[&str], catalog_hash: u64) -> String {
    let mut out = String::new();
    out.push_str(
        "//! Generated by `cargo run -p xtask -- iconify-catalog`. Do not edit by hand.\n\
         //!\n\
         //! Each set's accessors come from `__set_accessors!`, and only when the set's\n\
         //! feature is enabled.\n\n\
         #[allow(unused_imports)]\n\
         use crate::{Provider, missing};\n\
         #[allow(unused_imports)]\n\
         use aurora_iconify_macros::__set_accessors;\n\n",
    );
    let _ = writeln!(
        out,
        "/// Fingerprint of the icon catalog this crate was generated from.\n\
         pub const CATALOG_HASH: u64 = {catalog_hash:#x};\n"
    );
    out.push_str(
        "/// Identifies an icon set. Only the sets enabled by Cargo features have a variant.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n\
         pub enum SetId {\n",
    );
    for prefix in prefixes {
        let _ = writeln!(
            out,
            "    /// The `{prefix}` icon set.\n    #[cfg(feature = {prefix:?})]\n    {},",
            variant_name(prefix)
        );
    }
    out.push_str(
        "}\n\n\
         /// Whether the icon set `name` is enabled. `icon_sets!` checks each declared set with this.\n\
         #[doc(hidden)]\n\
         #[allow(unused_variables)] // With no sets enabled, `name` is never read.\n\
         pub const fn __set_enabled(name: &str) -> bool {\n",
    );
    // `str` cannot be matched in a `const fn`, so each enabled set is compared as bytes.
    for prefix in prefixes {
        let _ = writeln!(
            out,
            "    #[cfg(feature = {prefix:?})]\n    \
             if crate::bytes_equal(name.as_bytes(), {prefix:?}.as_bytes()) {{\n        \
             return true;\n    }}"
        );
    }
    out.push_str("    false\n}\n");
    for prefix in prefixes {
        let _ = writeln!(
            out,
            "\n#[cfg(feature = {prefix:?})]\n__set_accessors!({prefix:?});"
        );
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> SetData {
        SetData {
            prefix: "mage",
            names_text: "3d-rotate\nbox\nchart-fill\nby-name\n",
        }
    }

    #[test]
    fn output_is_valid_rust() {
        let code = facade_set_source(&sample(), "https://api.example");
        if let Err(e) = syn::parse_file(&code) {
            panic!("generated code does not parse: {e}\n{code}");
        }
    }

    #[test]
    fn every_name_gets_a_method_with_its_catalog_id() {
        let code = facade_set_source(&sample(), "https://api.example");
        assert!(code.contains("pub fn _3d_rotate(&self)"));
        assert!(code.contains("P::get(SetId::Mage, 0)"));
        assert!(code.contains("pub fn box_icon(&self)"));
        assert!(code.contains("P::get(SetId::Mage, 1)"));
        assert!(code.contains("pub fn chart_fill(&self)"));
        assert!(code.contains("P::get(SetId::Mage, 2)"));
        // `by-name` collides with the reserved lookup, so it gets no method.
        assert!(!code.contains("pub fn by_name(&self) "));
        assert!(code.contains("pub fn by_name(&self, name: &str)"));
    }

    #[test]
    fn previews_are_behind_their_feature() {
        let code = facade_set_source(&sample(), "https://api.example");
        assert!(code.contains(
            "#[cfg_attr(feature = \"previews\", doc = \"![box](https://api.example/mage/box.svg?width=48&height=48&color=white)\")]"
        ));
    }

    #[test]
    fn sets_module_lists_each_set_behind_its_feature() {
        let code = sets_module_source(&["lucide", "material-symbols"], 0xabc);
        if let Err(e) = syn::parse_file(&code) {
            panic!("generated module does not parse: {e}\n{code}");
        }
        assert!(code.contains("pub const CATALOG_HASH: u64 = 0xabc;"));
        assert!(code.contains("#[cfg(feature = \"lucide\")]\n    Lucide,"));
        assert!(code.contains("#[cfg(feature = \"material-symbols\")]\n    MaterialSymbols,"));
        assert!(code.contains(
            "#[cfg(feature = \"lucide\")]\n    if crate::bytes_equal(name.as_bytes(), \"lucide\".as_bytes()) {"
        ));
        assert!(code.contains(
            "#[cfg(feature = \"material-symbols\")]\n__set_accessors!(\"material-symbols\");"
        ));
    }
}
